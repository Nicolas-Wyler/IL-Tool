import assert from 'node:assert/strict';
import { zipFiles, matrixCSV, crc32, additiveRegions, intersectPolygon, polygonArea } from '../dist/export-data.js';
import { colorField } from '../dist/field.js';
import { gratingSquare } from '../dist/grating-geometry.js';
const square = (x, y, size) => [{x,y},{x:x+size,y},{x:x+size,y:y+size},{x,y:y+size}];
const regions = additiveRegions([{polygon:square(0,0,2),weight:.25},{polygon:square(1,0,2),weight:.75}]);
const areaAt = weight => regions.filter(r=>r.weight===weight).reduce((sum,r)=>sum+polygonArea(r.polygon),0);
assert.equal(areaAt(.25),2); assert.equal(areaAt(.75),2); assert.equal(areaAt(1),2);
assert.equal(polygonArea(intersectPolygon(square(0,0,2),square(1,1,2))),1);
const repeated = additiveRegions(Array.from({length:6},()=>({polygon:square(-1,-1,2),weight:1})));
assert.equal(repeated.length,1); assert.equal(repeated[0].weight,6);
const rotated = additiveRegions([0,60,120,180,240,300].map(azimuthDeg => ({weight:1,
  polygon:gratingSquare({wavelengthNm:3.1,pitchNm:Infinity,workingDistanceUm:0,widthUm:80,azimuthDeg}).corners})));
assert.ok(rotated.length < 100);
assert.ok(Math.abs(rotated.reduce((sum,r)=>sum+polygonArea(r.polygon)*r.weight,0)-6*80*80)<1e-7);
assert.equal(matrixCSV(2,2,i=>[1,-2,3.25,4][i]),'1,-2\n3.25,4\n');
assert.equal(crc32(new TextEncoder().encode('123456789')),0xcbf43926);
const zip = new Uint8Array(await (await zipFiles([{name:'a.csv',data:'1,2\n'},{name:'phase.csv',data:'0,3.14\n'}])).arrayBuffer());
const view = new DataView(zip.buffer);
assert.equal(view.getUint32(0,true),0x04034b50);
assert.equal(view.getUint32(zip.length-22,true),0x06054b50);
assert.equal(view.getUint16(zip.length-14,true),2);
const directory = view.getUint32(zip.length-6,true);
assert.equal(view.getUint32(directory,true),0x02014b50);
assert.equal(view.getUint32(directory+16,true),crc32(new TextEncoder().encode('1,2\n')));
const data = new Uint8ClampedArray(8);
colorField(new Float64Array([1,0]),new Float64Array([0,0]),'complex',4,data);
assert.deepEqual([...data],[64,0,0,255,0,0,0,255]);
colorField(new Float64Array([1,0]),new Float64Array([0,2]),'intensity',4,data);
assert.deepEqual([...data],[64,64,64,255,255,255,255,255]);
console.log('Passed: ZIP signatures and CRC, raw CSV matrices, exact vector overlap regions, viewport clipping, and shared field coloring.');
